# Building 1, Chapter 1 check: rearrangements.
from itertools import permutations, combinations
from math import factorial, lcm
from collections import Counter
def comp(s, t): return tuple(s[t[i]] for i in range(len(t)))      # s after t
def inv(s): return sum(1 for i in range(len(s)) for j in range(i+1, len(s)) if s[i] > s[j])
def inverse(s):
    r = [0]*len(s)
    for i, v in enumerate(s): r[v] = i
    return tuple(r)
def cycles(s):
    seen, out = set(), []
    for i in range(len(s)):
        if i not in seen:
            c, j = [], i
            while j not in seen: seen.add(j); c.append(j); j = s[j]
            out.append(len(c))
    return tuple(sorted(out, reverse=True))
def swap(n, i, j):
    s = list(range(n)); s[i], s[j] = s[j], s[i]; return tuple(s)
for n in range(1, 7):
    G = list(permutations(range(n))); e = tuple(range(n))
    assert len(G) == factorial(n)
    ok5 = all((inv(comp(a, b)) - inv(a) - inv(b)) % 2 == 0 for a in G for b in G) if n <= 5 else True
    # P6: closure of the swap gluing respecting composition = parity classes. Build union-find with generators: glue s~t for swaps, then close under left/right multiplication
    sw = [swap(n, i, j) for i in range(n) for j in range(i+1, n)]
    # closure via normal subgroup generated by s t^{-1}
    H = {e}; gens = [comp(s, inverse(sw[0])) for s in sw] if sw else []
    frontier = set(gens) | {e}
    while frontier:
        new = set()
        for a in frontier:
            for b in list(H | frontier):
                for c in (comp(a, b), comp(b, a)):
                    if c not in H and c not in frontier: new.add(c)
        H |= frontier; frontier = new - H
    H = {comp(comp(p, h), inverse(p)) for h in H for p in G}
    nbags = len(G)//len(H) if n >= 2 else 1
    even = {g for g in G if inv(g) % 2 == 0}
    types = Counter(cycles(g) for g in G)
    def size(t):
        m = Counter(t); d = 1
        for k, mk in m.items(): d *= k**mk*factorial(mk)
        return factorial(n)//d
    okP12 = all(types[t] == size(t) for t in types)
    okP11 = all((-1)**inv(g) == (-1)**(n - len(cycles(g))) for g in G)
    # T1 survey: unions of conjugacy classes containing e, closed under composition
    cls = {}
    for g in G: cls.setdefault(cycles(g), set()).add(g)
    keys = [k for k in cls if k != tuple([1]*n)]
    normals = 0
    for r in range(len(keys)+1):
        for sub in combinations(keys, r):
            N = set(cls[tuple([1]*n)]).union(*[cls[k] for k in sub])
            if all(comp(a, b) in N for a in N for b in N): normals += 1
    print("n=%d: |S_n|=n! True; parity respects o: %s; swap gluing gives %d bag(s), zero bag = even moves: %s; types p(n)=%d; P12 sizes: %s; P11 sign from type: %s; blurs respecting o: %d"
          % (n, ok5, nbags, (H == even) if n >= 2 else True, len(types), okP12, okP11, normals))
