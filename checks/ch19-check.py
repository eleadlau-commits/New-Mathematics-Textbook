# T8: blurs of Z_p respecting + and x, checked on the picture Z/p^K (ideals of Z/p^K are p^k Z/p^K)
def ideals(n):
    res = set()
    for g in range(n):   # every ideal of Z/n is generated by one element (Z/n is a picture of Z, Chapter 3 R1)
        res.add(frozenset((g*t) % n for t in range(n)))
    return res
