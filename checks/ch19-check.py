# no order: a negative integer is a square in Z_p
def has_sqrt_all_rungs(c, p, K):
    start = 1 if p > 2 else 3
    xs = [y for y in range(p**start) if (y*y - c) % p**start == 0]
    for k in range(start+1, K+1):
        xs = [y + t*p**(k-1) for y in xs for t in range(p) if ((y + t*p**(k-1))**2 - c) % p**k == 0]
        xs = sorted({y % p**k for y in xs})
        if not xs: return False
    return True
print("T7 negative squares: 1-p is a square through 20 rungs for p=3,5,7,11:", all(has_sqrt_all_rungs(1-p, p, 20) for p in (3,5,7,11)), "| -7 in Z_2 through 20 rungs:", has_sqrt_all_rungs(-7, 2, 20))
