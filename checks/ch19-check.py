def digits(x, p, k): return [(x // p**j) % p for j in range(k)]   # d_0, d_1, ...
def lift_sqrt(c, p, x0, K):
    # x0^2 = c mod p; lift rung by rung, keeping x = x0 mod p
    x = x0
    for k in range(2, K+1):
        m = p**k
        x = next(y for y in range(x, m, p**(k-1)) if (y*y - c) % m == 0)
    return x
